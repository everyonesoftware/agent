// Rolling consumption: independently measured segments, never a slope across resets.
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import vm from 'node:vm';
const source=(await readFile(new URL('../page.go',import.meta.url),'utf8')).split('// BEGIN usage history model')[1].split('// END usage history model')[0];
const context=vm.createContext({});vm.runInContext(source+'\nthis.model=usageHistoryModel;',context);
const now=2000000000, reset=now+7*86400;
const points=Array.from({length:1441},(_,i)=>{const before=i<1388;return {at:now-86400+i*60,remaining_percent:before?Math.max(0,9-i/20):100-3*(i-1388)/52,reset_at:before?now-52*60:reset}});
const data={provider:'chatgpt',remaining_percent:97,reset_at:reset,observed_at:now,stale:false,gap_seconds:180,points,forecast_points:points};
let model=context.model(data,'24h',now);
assert.equal(model.forecast.seconds,86340,'Keep both observed reset-delimited periods; omit the unmeasured reset interval');
assert.equal(model.forecast.consumed,12,'Sum 9% before reset and 3% after, not the replenishment');
assert.equal(model.forecast.rate,12/86340);
assert.ok(model.forecast.depletedSeconds>18*3600,'Disclose constrained idle time at zero');
assert.equal(model.forecast.resetCount,1);
assert.ok(model.forecast.end.remaining_percent>12,'Do not promote the current session to a sustained daily average');
for(const range of ['week','period'])assert.equal(context.model(data,range,now).forecast.rate,model.forecast.rate,'Chart range must not change rate');
const delayed=context.model(data,'24h',now+120);assert.equal(delayed.forecast.rate,model.forecast.rate,'Unobserved delayed-poll time is not idle evidence');
console.log('PASS cross-reset rolling-day consumption retains quiet and depleted intervals');
const gapPoints=points.filter((_,i)=>i<600||i>659);
const partial=context.model({...data,forecast_points:gapPoints},'24h',now).forecast;
assert.equal(partial.seconds,86340-61*60,'Exclude the entire missing interval from elapsed coverage');
assert.equal(partial.consumed,12,'A gap during the depleted interval contributes neither usage nor idle time');
assert.equal(partial.lookback,86400,'Lookback and covered duration are distinct');
const changed=points.map((p,i)=>({...p,window_minutes:i<1388?10080:300}));
const comparable=context.model({...data,forecast_points:changed},'24h',now).forecast;
assert.equal(comparable.seconds,52*60,'Do not combine different allowance definitions under a reused window ID');
assert.equal(comparable.consumed,3);
const unknown=context.model({...data,stale:true,sessions:[{start_at:now-60,end_at:now,used_percent:1,current:true,estimated:true}]},'24h',now);
assert.equal(unknown.forecast,null);
assert.equal(unknown.sessions[0].current,false,'Stale evidence cannot identify a current session');
console.log('PASS coverage gaps, changed quota definitions and stale session labels');
const idleLedger=context.model({provider:'brave',observed_at:now,reset_at:reset,remaining_percent:31,points:[{at:now-172800,remaining_percent:31,reset_at:reset}]},'24h',now).forecast;
assert.equal(idleLedger.seconds,86400);
assert.equal(idleLedger.lookback,86400,'A complete local ledger observes idle time through Now even without recent requests');
const ledgerCutoff=context.model({provider:'brave',observed_at:now,reset_at:reset,remaining_percent:70,points:[{at:now-90000,remaining_percent:100,reset_at:reset},{at:now-86400,remaining_percent:90,reset_at:reset},{at:now-86399,remaining_percent:80,reset_at:reset},{at:now,remaining_percent:70,reset_at:reset}]},'24h',now).forecast;
assert.equal(ledgerCutoff.seconds,86400);
assert.equal(ledgerCutoff.consumed,20,'Ledger consumption is attributed to events after the cutoff, not interpolated through idle time');
